// Offline, deterministic extraction from the pinned MaNGOS snapshot. No C++
// handler bodies are translated, and no opcode numbers are maintained by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const commit = 'b2083578a279aac3a70a2cba8fe710a454324c4e';
const manifest = JSON.parse(readFileSync(resolve(root, 'tools/reference/mangos/manifest.json')));
function source(name) {
  const data = readFileSync(resolve(root, 'tools/reference/mangos', name));
  if (createHash('sha256').update(data).digest('hex') !== manifest[name]) throw Error(`Reference checksum mismatch: ${name}`);
  return data.toString('utf8');
}
const header = source('Opcodes.h');
const body = header.match(/enum OpcodesList\s*\{([\s\S]*?)\};/)[1];
const entries = [...body.matchAll(/^\s*([A-Z][A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+)\s*,?/gm)];
const count = Number(header.match(/#define NUM_MSG_TYPES\s+(0x[0-9A-Fa-f]+)/)[1]);
if (entries.length !== count) throw Error('Unexpected opcode count');
const table = source('OpcodeTable.cpp');
const rows = [...table.matchAll(/^\s*OPCODE\(\s*(\w+),\s*(STATUS_\w+),\s*(PROCESS_\w+),\s*&WorldSession::\w+\s*\);/gm)];
const metadata = new Map(rows.map(([,name,status,mode]) => [name,{status,mode}]));
if (metadata.size !== rows.length || rows.length !== entries.length) throw Error('Missing/duplicate opcode registrations');
const seen = new Set();
let output = `// Code generated by tools/generate-opcodes.mjs; DO NOT EDIT.\n// SPDX-License-Identifier: GPL-3.0-or-later\n// MaNGOS ${commit}: src/proto/Opcodes.h and src/game/Server/OpcodeTable.cpp.\npackage opcodes\n\nconst (\n`;
for (const [,name,value] of entries) {
  const id = Number(value);
  if (seen.has(id) || id >= count || !metadata.has(name)) throw Error(`Invalid opcode ${name}`);
  seen.add(id);
  output += `${name} uint32 = ${value}\n`;
}
output += `NUM_MSG_TYPES = ${count}\n)\n\nvar catalogue = [NUM_MSG_TYPES]Metadata{\n`;
for (const [,name] of entries) {
  const {status,mode} = metadata.get(name);
  if (!/^STATUS_(AUTHED|LOGGEDIN|TRANSFER|LOGGEDIN_OR_RECENTLY_LOGGEDOUT|NEVER|UNHANDLED)$/.test(status) || !/^PROCESS_(INPLACE|THREADUNSAFE|THREADSAFE)$/.test(mode)) throw Error('Unknown policy');
  output += `${name}: {Name: "${name}", Status: ${status}, Processing: ${mode}},\n`;
}
output += '}\n';
output = execFileSync('gofmt', [], {input:output, encoding:'utf8'});
const target = resolve(root,'internal/protocol/world/tbc/opcodes/opcodes_gen.go');
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8').replaceAll('\r\n','\n') !== output.replaceAll('\r\n','\n')) throw Error('Generated opcodes are stale');
} else {
  writeFileSync(target,output);
}
console.log(`${entries.length} opcode constants and policies verified (${commit})`);
